#!/usr/bin/env bash
# A Mouse Borders lab on one machine: two Aujar daemons ("lab-a" and "lab-b"), each with its own
# settings, state, socket and ports, paired with each other over 127.0.0.1.
#
#   scripts/mwb-lab.sh up          build, start both daemons, pair them, show the status
#   scripts/mwb-lab.sh status      both sides' status
#   scripts/mwb-lab.sh a mwb ...   run an `aujar` command against daemon A   (e.g. a mwb doctor)
#   scripts/mwb-lab.sh b mwb ...   run an `aujar` command against daemon B
#   scripts/mwb-lab.sh logs a|b    follow a daemon's log
#   scripts/mwb-lab.sh send        send a test file from A to B and check it arrived
#   scripts/mwb-lab.sh smoke       up -> connected -> send a file -> down; exit 1 on failure
#   scripts/mwb-lab.sh down        stop both daemons (the lab directory is kept)
#   scripts/mwb-lab.sh clean       stop and delete the lab directory
#
# What it is for: pairing, the key, the connection and reconnects, file transfer, status, the
# audit log, settings changes, protocol changes. What it is NOT for: moving the pointer or the
# keyboard between machines. That needs two real computers: see docs/MOUSE_BORDERS.md.
#
# Safety: the lab daemons run without a graphical session (no DISPLAY/WAYLAND_DISPLAY),
# without the global shortcut, with edge switching, the clipboard, screensaver blocking and
# remote lock turned off. But Linux input capture (evdev/uinput) does not need a display: if your
# account has that access (the `input` group, /dev/uinput), the lab refuses to start, because
# two daemons could then grab your real keyboard. Override with MWB_LAB_FORCE=1 and do not press
# Ctrl+Alt+digits/E/L/R/M while it runs.
#
# Environment: AUJAR_LAB_DIR (default /tmp/aujar-lab), AUJAR_LAB_PORT_A (25101),
# AUJAR_LAB_PORT_B (25201); each daemon also uses the port above plus one.
set -euo pipefail

cd "$(dirname "$0")/.."

LAB="${AUJAR_LAB_DIR:-/tmp/aujar-lab}"
PORT_A="${AUJAR_LAB_PORT_A:-25101}"
PORT_B="${AUJAR_LAB_PORT_B:-25201}"

die() {
    echo "error: $*" >&2
    exit 1
}
have() { command -v "$1" >/dev/null 2>&1; }

# ---- helpers -----------------------------------------------------------------------------

input_access() {
    [ -w /dev/uinput ] && return 0
    local device
    for device in /dev/input/event*; do
        [ -r "$device" ] && return 0
    done
    return 1
}

build() {
    have cargo || die "cargo not found; run ./scripts/setup-dev.sh"
    cargo build -q -p aujar-launcher-app
    local target
    target="$(cargo metadata --format-version 1 --no-deps 2>/dev/null |
        grep -o '"target_directory":"[^"]*"' | head -1 | cut -d'"' -f4)"
    AUJAR="${target:-target}/debug/aujar"
    [ -x "$AUJAR" ] || die "built binary not found at $AUJAR"
}

port_of() { [ "$1" = a ] && echo "$PORT_A" || echo "$PORT_B"; }
peer_of() { [ "$1" = a ] && echo b || echo a; }

# The environment that makes a process "machine n": its own settings, state and socket, no
# graphical session, no global shortcut.
ENV_ARGS=()
machine_env() {
    local n="$1"
    ENV_ARGS=(
        env -u DISPLAY -u WAYLAND_DISPLAY
        XDG_SESSION_TYPE=tty
        XDG_CONFIG_HOME="$LAB/$n/config"
        XDG_STATE_HOME="$LAB/$n/state"
        AUJAR_SOCKET="$LAB/$n/aujar.sock"
        AUJAR_NO_HOTKEYS=1
        RUST_LOG="${RUST_LOG:-info,aujar_mouse_borders=debug,aujar_daemon=debug}"
    )
}

# Run the aujar binary as one of the two machines.
as() {
    local n="$1"
    shift
    machine_env "$n"
    "${ENV_ARGS[@]}" "$AUJAR" "$@"
}

write_settings() {
    local n="$1" p
    p="$(peer_of "$n")"
    mkdir -p "$LAB/$n/config/aujar" "$LAB/$n/state" "$LAB/$n/received"
    cat >"$LAB/$n/config/aujar/settings.toml" <<EOF
# Generated by scripts/mwb-lab.sh; rewritten on every \`up\`.
[mouse_borders]
enabled = true
machine_name = "lab-$n"
port = $(port_of "$n")
matrix = "row"
# Nothing here may touch the real desktop.
easy_mouse = "disabled"
edge_portal = false
share_clipboard = false
block_screensaver = false
allow_remote_lock = false
# Both daemons are on loopback.
same_subnet_only = false
transfer_files = true
max_file_mb = 100
receive_dir = "$LAB/$n/received"

[[mouse_borders.machines]]
name = "lab-a"
slot = 0
$([ "$n" = b ] && echo "address = \"127.0.0.1:$PORT_A\"")

[[mouse_borders.machines]]
name = "lab-b"
slot = 1
$([ "$n" = a ] && echo "address = \"127.0.0.1:$PORT_B\"")
EOF
}

running() {
    local pidfile="$LAB/$1/pid"
    [ -f "$pidfile" ] && kill -0 "$(cat "$pidfile")" 2>/dev/null
}

start_daemon() {
    local n="$1"
    running "$n" && {
        echo "lab-$n already running"
        return 0
    }
    rm -f "$LAB/$n/aujar.sock"
    machine_env "$n"
    # exec: the background process becomes the daemon itself, so the saved PID is its PID.
    (exec "${ENV_ARGS[@]}" "$AUJAR" daemon </dev/null >>"$LAB/$n/daemon.log" 2>&1) &
    echo $! >"$LAB/$n/pid"
    disown 2>/dev/null || true
    local _
    for _ in $(seq 1 100); do
        [ -S "$LAB/$n/aujar.sock" ] && return 0
        running "$n" || die "lab-$n exited at startup; see $LAB/$n/daemon.log"
        sleep 0.1
    done
    die "lab-$n did not create its socket; see $LAB/$n/daemon.log"
}

stop_daemon() {
    local n="$1" pid
    if running "$n"; then
        pid="$(cat "$LAB/$n/pid")"
        kill -TERM "$pid" 2>/dev/null || true
        local _
        for _ in $(seq 1 50); do
            kill -0 "$pid" 2>/dev/null || break
            sleep 0.1
        done
        kill -KILL "$pid" 2>/dev/null || true
        echo "stopped lab-$n"
    fi
    rm -f "$LAB/$n/pid" "$LAB/$n/aujar.sock"
}

wait_connected() {
    local timeout="${1:-30}" _
    for _ in $(seq 1 "$((timeout * 2))"); do
        if as a mwb status 2>/dev/null | grep -qE 'lab-b +connected( |$)' &&
            as b mwb status 2>/dev/null | grep -qE 'lab-a +connected( |$)'; then
            return 0
        fi
        sleep 0.5
    done
    return 1
}

# ---- commands ----------------------------------------------------------------------------

cmd_up() {
    if input_access && [ "${MWB_LAB_FORCE:-0}" != 1 ]; then
        die "this account can capture and inject input (/dev/uinput or /dev/input/event*).
Two lab daemons could grab your real keyboard. Test with a user without that access,
or accept the risk with MWB_LAB_FORCE=1 (and do not press the Ctrl+Alt hotkeys)."
    fi

    build
    mkdir -p "$LAB"
    write_settings a
    write_settings b
    start_daemon a
    start_daemon b

    # One key for both: generate on A, store on B (what two real machines do).
    if ! as a mwb key show >/dev/null 2>&1; then
        as a mwb key generate >/dev/null
    fi
    local key
    key="$(as a mwb key show)"
    as b mwb key set "$key" >/dev/null 2>&1 || as b mwb key set "$key" --force >/dev/null
    as a mwb reload >/dev/null 2>&1 || true
    as b mwb reload >/dev/null 2>&1 || true

    echo "waiting for the machines to connect..."
    if wait_connected 30; then
        echo "connected."
    else
        echo "not connected after 30 s. Status and logs follow; see $LAB/a/daemon.log and b." >&2
    fi
    echo
    cmd_status
}

cmd_status() {
    local n
    for n in a b; do
        echo "=== lab-$n  (AUJAR_SOCKET=$LAB/$n/aujar.sock) ==="
        if running "$n"; then
            as "$n" mwb status || true
        else
            echo "not running"
        fi
        echo
    done
}

cmd_send() {
    running a && running b || die "the lab is not running: scripts/mwb-lab.sh up"
    local file="$LAB/a/lab-test-file.txt" name
    name="$(basename "$file")"
    echo "hello from lab-a at $(date -u +%FT%TZ)" >"$file"
    rm -f "$LAB/b/received/$name"
    as a mwb send lab-b "$file"

    local _
    for _ in $(seq 1 40); do
        if [ -f "$LAB/b/received/$name" ] && cmp -s "$file" "$LAB/b/received/$name"; then
            echo "ok: $LAB/b/received/$name arrived intact"
            return 0
        fi
        sleep 0.25
    done
    echo "FAILED: the file did not arrive in $LAB/b/received" >&2
    return 1
}

cmd_smoke() {
    local status=0
    cmd_up >/dev/null || status=1
    if [ "$status" -eq 0 ]; then
        wait_connected 5 || {
            echo "FAILED: machines are not connected" >&2
            status=1
        }
    fi
    if [ "$status" -eq 0 ]; then
        cmd_send || status=1
    fi
    if [ "$status" -ne 0 ]; then
        echo "--- lab-a log (tail)" >&2
        tail -n 20 "$LAB/a/daemon.log" 2>/dev/null >&2 || true
        echo "--- lab-b log (tail)" >&2
        tail -n 20 "$LAB/b/daemon.log" 2>/dev/null >&2 || true
    fi
    cmd_down
    [ "$status" -eq 0 ] && echo "smoke test passed" || echo "smoke test FAILED" >&2
    return "$status"
}

cmd_down() {
    stop_daemon a
    stop_daemon b
}

cmd_clean() {
    cmd_down
    rm -rf "$LAB"
    echo "removed $LAB"
}

case "${1:-}" in
    up) cmd_up ;;
    status) cmd_status ;;
    send) build && cmd_send ;;
    smoke) cmd_smoke ;;
    down) cmd_down ;;
    clean) cmd_clean ;;
    a | b)
        n="$1"
        shift
        [ "$#" -gt 0 ] || die "usage: scripts/mwb-lab.sh $n <aujar arguments>, e.g. $n mwb status"
        build
        as "$n" "$@"
        ;;
    logs)
        [ "${2:-}" = a ] || [ "${2:-}" = b ] || die "usage: scripts/mwb-lab.sh logs a|b"
        exec tail -n 50 -f "$LAB/$2/daemon.log"
        ;;
    -h | --help | help | "")
        sed -n '2,27p' "$0" | sed 's/^# \{0,1\}//'
        ;;
    *)
        die "unknown command: $1 (try --help)"
        ;;
esac
